package com.ozonehis.cli;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The distro build's inheritance step: merges the parent distro's resolved
 * files (the parent's whole chain, already resolved) with this distro's own
 * sources, writing the result to meta/resolved/ - the only vars and
 * model source read at deployment. Sources are never read at run time and
 * never modified here; the output is a generated, comment-free copy.
 *
 * One-sided cases are the inheritance rules: a parent file with no own
 * counterpart is inherited as-is; an own file with no parent counterpart
 * is published as-is (the Ozone root distro).
 *
 * The build also records the distro's identity (name, version,
 * description) here, as resolved/info.yml - the deployment's declared
 * source of the compose project name.
 */
final class DistroMerge {

    private static final String[] MERGED_FILES = {"vars.yml", "model-overrides.yml"};

    private DistroMerge() {
    }

    /**
     * @param parentDistroDir optional: the parent distro's assembled dir,
     *                         must carry meta/resolved/
     * @param distroDir        this distro's assembled dir
     * @return the resolved files written
     */
    static List<File> merge(File parentDistroDir, File distroDir) throws IOException {
        return merge(parentDistroDir, distroDir, new LinkedHashMap<String, String>());
    }

    /**
     * @param info the distro's identity (name, version, description) as
     *             declared by the build; recorded as resolved/info.yml
     */
    static List<File> merge(File parentDistroDir, File distroDir, Map<String, String> info) throws IOException {
        File metaDir = new File(distroDir, "meta");
        File resolvedDir = new File(metaDir, "resolved");

        Map<String, File> parentFiles = new LinkedHashMap<String, File>();
        if (parentDistroDir != null) {
            File parentResolved = new File(parentDistroDir, "meta/resolved");
            for (String name : MERGED_FILES) {
                File file = new File(parentResolved, name);
                if (file.isFile()) {
                    parentFiles.put(name, file);
                }
            }
            if (parentFiles.isEmpty()) {
                throw new IOException("No resolved files in the parent distro: " + parentResolved
                        + ". It is not a built distro artifact - run its build, or: ozone resolve --to <parent-distro-dir>");
            }
        }

        List<File> written = new ArrayList<File>();
        for (String name : MERGED_FILES) {
            File own = new File(metaDir, name);
            File parent = parentFiles.get(name);
            if (parent == null && !own.isFile()) {
                continue; // nothing at any level: not written
            }
            Map<String, Object> merged;
            if (parent == null) {
                merged = Yamls.load(own);
            } else if (!own.isFile()) {
                merged = Yamls.load(parent);
            } else {
                merged = YamlMerge.merge(Yamls.load(parent), Yamls.load(own), name);
            }
            resolvedDir.mkdirs();
            File out = new File(resolvedDir, name);
            write(out, merged);
            written.add(out);
        }

        if (!info.isEmpty()) {
            resolvedDir.mkdirs();
            File out = new File(resolvedDir, "info.yml");
            write(out, new LinkedHashMap<String, Object>(info));
            written.add(out);
        }

        if (written.isEmpty()) {
            throw new IOException("Nothing to merge in " + distroDir + ": no own meta/vars.yml or"
                    + " meta/model-overrides.yml, no parent resolved files, and no distro identity to record.");
        }
        return written;
    }

    private static void write(File out, Map<String, Object> merged) throws IOException {
        StringBuilder content = new StringBuilder();
        content.append("# Generated by 'ozone resolve' - do not edit. Regenerate with: 'ozone resolve'\n");
        content.append(Yamls.dump(merged));
        Files.write(out.toPath(), content.toString().getBytes(StandardCharsets.UTF_8));
    }
}
